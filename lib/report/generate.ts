import type { ScenarioResult, Severity } from '@/lib/engine/types';

export interface ReportRun {
    scenarioName: string;
    target: string;
    status: string;
    results: ScenarioResult[];
}

export interface ReportInput {
    engagementName: string;
    mode: string;
    generatedAt?: string;
    runs: ReportRun[];
}

const SEV_ORDER: Severity[] = ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'INFO'];

export function buildReport(input: ReportInput): string {
    const all = input.runs.flatMap((r) => r.results);
    const when = input.generatedAt || new Date().toISOString();

    const bySeverity = (s: Severity) => all.filter((r) => r.severity === s && r.outcome !== 'SECURE' && r.outcome !== 'INFO').length;
    const proven = all.filter((r) => r.outcome === 'PROVEN');
    const vulnerable = all.filter((r) => r.outcome === 'VULNERABLE');
    const blocked = input.runs.filter((r) => r.status === 'BLOCKED');

    const tactics = new Set(all.map((r) => r.attckTactic).filter(Boolean) as string[]);

    const lines: string[] = [];
    lines.push(`# Breach Simulation Report: ${input.engagementName}`);
    lines.push('');
    lines.push(`Generated: ${when}  `);
    lines.push(`Mode: ${input.mode}  `);
    lines.push(`Scenarios run: ${input.runs.length}  `);
    lines.push('');

    lines.push('## Executive summary');
    lines.push('');
    lines.push(`This engagement produced **${vulnerable.length} confirmed weaknesses** and **${proven.length} non-destructive proofs** of access.`);
    lines.push('');
    lines.push('| Severity | Confirmed |');
    lines.push('| --- | --- |');
    for (const s of SEV_ORDER) lines.push(`| ${s} | ${bySeverity(s)} |`);
    lines.push('');
    if (tactics.size) {
        lines.push(`MITRE ATT&CK tactics exercised: ${Array.from(tactics).join(', ')}.`);
        lines.push('');
    }

    if (proven.length) {
        lines.push('## Proven access (non-destructive)');
        lines.push('');
        lines.push('Each item below was confirmed by reaching the target, running a read-only command, or reading metadata only. No data was copied and nothing was changed.');
        lines.push('');
        for (const p of proven) {
            lines.push(`### ${p.title}`);
            lines.push(`- Severity: ${p.severity}`);
            if (p.attckTechnique) lines.push(`- ATT&CK: ${p.attckTactic} / ${p.attckTechnique}`);
            if (p.target) lines.push(`- Target: ${p.target}`);
            if (p.evidence) lines.push(`- Evidence:\n\n\`\`\`\n${p.evidence}\n\`\`\``);
            if (p.remediation) lines.push(`- Remediation: ${p.remediation}`);
            lines.push('');
        }
    }

    lines.push('## Findings by severity');
    lines.push('');
    for (const s of SEV_ORDER) {
        const items = vulnerable.filter((r) => r.severity === s);
        if (!items.length) continue;
        lines.push(`### ${s}`);
        lines.push('');
        for (const f of items) {
            lines.push(`- **${f.title}**${f.target ? ` (${f.target})` : ''}`);
            if (f.evidence) lines.push(`  - ${f.evidence.replace(/\n/g, ' ')}`);
            if (f.remediation) lines.push(`  - Fix: ${f.remediation}`);
        }
        lines.push('');
    }

    if (blocked.length) {
        lines.push('## Blocked by safety gates');
        lines.push('');
        lines.push('These scenarios did not run because scope or authorization checks refused them:');
        lines.push('');
        for (const b of blocked) lines.push(`- ${b.scenarioName} against ${b.target}`);
        lines.push('');
    }

    lines.push('---');
    lines.push('_Generated by Mini ASM breach simulation engine. Authorized testing only._');
    return lines.join('\n');
}

export function reportSummaryJson(input: ReportInput) {
    const all = input.runs.flatMap((r) => r.results);
    return {
        engagement: input.engagementName,
        mode: input.mode,
        scenarios: input.runs.length,
        proven: all.filter((r) => r.outcome === 'PROVEN').length,
        vulnerable: all.filter((r) => r.outcome === 'VULNERABLE').length,
        blocked: input.runs.filter((r) => r.status === 'BLOCKED').length,
        bySeverity: SEV_ORDER.reduce<Record<string, number>>((acc, s) => {
            acc[s] = all.filter((r) => r.severity === s && r.outcome === 'VULNERABLE').length;
            return acc;
        }, {}),
    };
}
